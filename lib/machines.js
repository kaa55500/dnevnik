// Шкалы стопок, где номер плиты не равен килограммам. Индекс в массиве плюс
// один — номер ячейки, значение — выбранный вес в килограммах. Стопки,
// подписанные сразу в килограммах (Kraft, Хаммер), сюда не попадают:
// там подсказка «ячейка» противоречила бы правилу журнала.
export const MACHINES = {
  "Hoist HS-1310": [5.4, 9.1, 12.7, 16.3, 20.4, 24, 29.5, 35.4, 40.8, 46.7, 52.2, 58, 63.5, 69.4, 74.8, 80.7],
  "Hoist HD1610": [20.4, 29.5, 38.6, 47.6, 56.7, 65.8, 74.8, 83.9, 93, 102.1, 111.1, 120.2, 129.3, 138.3, 147.4, 156.5, 165.6, 174.6, 183.7, 192.8, 201.8],
};

/**
 * Ближайшая ячейка под выставленный вес. Точного совпадения не требуется:
 * подсказка нужнее всего тогда, когда не помнишь, на что ставить, а шаг
 * у HD1610 — 9,1 кг, и половина осмысленных чисел лежит между плитами.
 */
export function cellFor(model, kg) {
  const plates = MACHINES[model];
  if (!plates || kg == null || !Number.isFinite(kg)) return null;
  let best = 0;
  for (let i = 1; i < plates.length; i += 1) {
    if (Math.abs(plates[i] - kg) < Math.abs(plates[best] - kg)) best = i;
  }
  return { cell: best + 1, kg: plates[best], exact: Math.abs(plates[best] - kg) < 0.05 };
}

/** Подпись для экрана: «(ячейка 13)» или «(≈ ячейка 13)». */
export function cellHint(model, kg) {
  const hit = cellFor(model, kg);
  if (!hit) return '';
  return '(' + (hit.exact ? '' : '≈ ') + 'ячейка ' + hit.cell + ')';
}
